# -*- coding: utf-8 -*-
"""从大厅本地缓存解出勋章/称号图标并更新 Rust 启动器资源索引。

这些单图 SWF 使用非标准结束标签封装 JPEG 与独立 alpha 数据；FFDec 可读主
MedalAssets 资源库，但单图包需按 SWF CWS 结构取出 JPEG/alpha 后再写 PNG。
"""
from __future__ import annotations

import io
import json
import re
import zlib
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / "_work" / "lobby_host" / "cache"
LAUNCHER = ROOT / "lobby-launcher"
PREVIEW_ROOT = LAUNCHER / "assets" / "previews"
RUST_OUTPUT = LAUNCHER / "src" / "previews_collectibles.rs"
INVENTORY_PATHS = [
    LAUNCHER / "data" / "asset_inventory.json",
    ROOT / "Game-SSJJ" / "data" / "asset_inventory.json",
]

SOURCES = {
    "medals": re.compile(r"^resource_swf_MedalAssets_charInfoIcon_medal_(\d+)\.swf$"),
    "titles": re.compile(r"^resource_swf_titleIcon_title_(\d+)\.swf$"),
}


def extract_png(source: Path, target: Path) -> None:
    data = source.read_bytes()
    if len(data) < 8 or data[:3] != b"CWS":
        raise ValueError("不是可识别的 CWS SWF")
    body = zlib.decompress(data[8:])
    start = body.find(b"\xff\xd8")
    end_marker = body.find(b"\xff\xd9", start + 2)
    if start < 0 or end_marker < 0:
        raise ValueError("SWF 内未找到完整 JPEG 图像")
    end = end_marker + 2
    image = Image.open(io.BytesIO(body[start:end])).convert("RGBA")
    alpha_payload = body[end:]
    try:
        alpha = zlib.decompress(alpha_payload)
    except zlib.error:
        alpha = b""
    if len(alpha) == image.width * image.height:
        image.putalpha(Image.frombytes("L", image.size, alpha))
    target.parent.mkdir(parents=True, exist_ok=True)
    image.save(target, format="PNG", optimize=True)


def build() -> tuple[dict[str, dict[str, dict]], int]:
    assets: dict[str, dict[str, dict]] = {"medals": {}, "titles": {}}
    for category, pattern in SOURCES.items():
        out_dir = PREVIEW_ROOT / category
        for source in sorted(CACHE.glob("*.swf")):
            match = pattern.match(source.name)
            if not match:
                continue
            key = match.group(1)
            filename = f"{category[:-1]}_{key}.png"
            target = out_dir / filename
            extract_png(source, target)
            assets[category][key] = {
                "name": f"{'勋章' if category == 'medals' else '称号'} {key}",
                "complete": True,
                "preview_available": True,
                "client_available": None,
                "preview": f"assets/previews/{category}/{filename}",
                "source": source.name,
            }

    for path in INVENTORY_PATHS:
        if not path.is_file():
            continue
        inventory = json.loads(path.read_text(encoding="utf-8"))
        inventory.update(assets)
        path.write_text(
            json.dumps(inventory, ensure_ascii=False, indent=1, sort_keys=True) + "\n",
            encoding="utf-8",
        )

    lines = [
        "// Generated by Game-SSJJ/tools/build_lobby_collectibles.py; do not edit.",
        "pub fn bytes(kind: &str, key: &str) -> Option<&'static [u8]> {",
        "    match (kind, key) {",
    ]
    for category, items in assets.items():
        kind = "medal" if category == "medals" else "title"
        folder = category
        for key in sorted(items, key=lambda value: int(value)):
            filename = f"{category[:-1]}_{key}.png"
            lines.append(
                f'        ("{kind}", "{key}") => '
                f'Some(include_bytes!("../assets/previews/{folder}/{filename}")), '
            )
    lines.extend(["        _ => None,", "    }", "}", ""])
    RUST_OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    return assets, sum(len(items) for items in assets.values())


if __name__ == "__main__":
    indexed, count = build()
    print(
        "collectibles indexed:",
        "medals=", len(indexed["medals"]),
        "titles=", len(indexed["titles"]),
        "previews=", count,
    )
